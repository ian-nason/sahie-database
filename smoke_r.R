args <- commandArgs(TRUE)
if (length(args)>=3 && nzchar(args[[3]])) .libPaths(c(args[[3]],.libPaths()))
library(datapond)
library(DBI)
options(datapond.registry_url=args[[1]],datapond.cache_dir=args[[2]])
probe <- dbConnect(duckdb::duckdb())
stopifnot(dbGetQuery(probe,"SELECT installed FROM duckdb_extensions() WHERE extension_name='httpfs'")$installed[[1]])
dbDisconnect(probe,shutdown=TRUE)
stopifnot(identical(dp_list(),'sahie'))
con <- dp_connect('sahie',quiet=TRUE)
tryCatch({
 dbExecute(con,"SET memory_limit='128MiB'")
 dbExecute(con,'SET threads=1')
 dbExecute(con,"SET max_temp_directory_size='0B'")
 stopifnot(dbGetQuery(con,'SELECT count(*) AS n FROM estimates')$n==402786)
 stopifnot(dbGetQuery(con,'SELECT count(*) AS n FROM county_uninsured')$n==3144)
 stopifnot(nrow(dp_describe(con))==3)
 stopifnot(nrow(dp_describe(con,table='estimates'))==27)
 stopifnot(dbGetQuery(con,"SELECT count(*) AS n FROM county_uninsured WHERE fips='15005' AND pctui IS NULL")$n==1)
 leading<-dbGetQuery(con,"SELECT fips,pctui FROM county_uninsured WHERE fips='01001'")
 stopifnot(identical(leading$fips,'01001'),is.numeric(leading$pctui))
 example<-dbGetQuery(con,"SELECT fips,county_name,pctui,pctui_moe FROM county_uninsured WHERE statefips='36' ORDER BY fips LIMIT 3")
 cat(jsonlite::toJSON(list(passed=TRUE,client='R datapond',version=as.character(packageVersion('datapond')),R=R.version.string,duckdb=as.character(packageVersion('duckdb')),example=example),auto_unbox=TRUE))
},finally=dp_disconnect(con))
